#include<iostream>
using namespace std;

int main()
{
    int a = 1;
    int b = 0;

    // Logical AND
    cout << "Logical AND: " << (a && b) << endl;

    // Logical OR
    cout << "Logical OR: " << (a || b) << endl;

    // Logical NOT
    cout << "Logical NOT: " << (!a) << endl;

    return 0;
}