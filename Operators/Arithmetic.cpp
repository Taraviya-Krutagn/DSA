#include<iostream>
using namespace std;

int main()
{
    int a = 7;
    int b = 9;

    // Addition
    cout << "Addition: " << a + b << endl;

    // Subtraction
    cout << "Subtraction: " << a - b << endl;

    // Multiplication
    cout << "Multiplication: " << a * b << endl;

    // Division
    cout << "Division: " << a / b << endl;

    // Modulus
    cout << "Modulus: " << a % b << endl;

    // Increment

    // Pre-increment
    cout << "Increment: " << ++a << endl;
    // Post-increment
    cout << "Increment: " << a++ << endl;

    // Decrement

    // Pre-decrement
    cout << "Decrement: " << --b << endl;
    // Post-decrement
    cout << "Decrement: " << b-- << endl;

    return 0;
}